import AppKit
import CryptoKit

/// 只保存我们能稳定回放的表示；不保留浏览器、Office 等应用的私有剪贴板格式。
struct ClipboardContent: Codable, Equatable, Sendable {
    let type: String
    let data: Data
}

struct ClipboardItem: Codable, Equatable, Identifiable, Sendable {
    var id = UUID()
    let contents: [ClipboardContent]
    let fingerprint: String
    var copiedAt: Date
    var sourceApp: String?
    var isPinned = false

    init(contents: [ClipboardContent], sourceApp: String?, at: Date = Date()) {
        self.contents = contents.sorted { $0.type < $1.type }
        self.sourceApp = sourceApp
        copiedAt = at
        var hash = SHA256()
        for content in self.contents {
            // 长度前缀区分「一个表示的正文」和「多个表示的拼接」。
            for length in [content.type.utf8.count, content.data.count] {
                var encoded = UInt64(length).bigEndian
                withUnsafeBytes(of: &encoded) { hash.update(data: Data($0)) }
            }
            hash.update(data: Data(content.type.utf8))
            hash.update(data: content.data)
        }
        fingerprint = hash.finalize().map { String(format: "%02x", $0) }.joined()
    }

    var byteCount: Int { contents.reduce(0) { $0 + $1.data.count } }
    var text: String? {
        contents.first { $0.type == NSPasteboard.PasteboardType.string.rawValue }
            .flatMap { String(data: $0.data, encoding: .utf8) }
    }
    var imageData: Data? {
        contents.first { $0.type == NSPasteboard.PasteboardType.png.rawValue }?.data
            ?? contents.first { $0.type == NSPasteboard.PasteboardType.tiff.rawValue }?.data
    }
    var title: String {
        guard let text, !text.isEmpty else { return imageData == nil ? "文本内容" : "图片" }
        // 按 Unicode scalar 限长，避免一个超长组合字符撑满列表。
        return String(String.UnicodeScalarView(text.unicodeScalars.prefix(240)))
            .replacingOccurrences(of: "\n", with: " ")
            .replacingOccurrences(of: "\r", with: " ")
            .replacingOccurrences(of: "\t", with: " ")
    }
    func matches(_ query: String) -> Bool {
        query.isEmpty || (text ?? "").localizedStandardContains(query)
            || (sourceApp ?? "").localizedStandardContains(query)
            || (imageData != nil && "图片".contains(query))
    }
}

/// Maccy 的类型排除和多表示回放方式是本模块的参考来源，见 ThirdParty/Maccy-LICENSE.txt。
@MainActor
enum ClipboardCapture {
    static let ownType = NSPasteboard.PasteboardType("com.lizhiming.RestBreak.clipboard-history")
    static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    static let maxItemBytes = 8 * 1024 * 1024
    static let ignoredTypes: Set<String> = [
        ownType.rawValue, concealedType.rawValue, "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
        "com.typeit4me.clipping", "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type", "net.antelle.keeweb"
    ]

    enum Result {
        case item(ClipboardItem), ignored, tooLarge, changedDuringRead
    }

    static func read(_ board: NSPasteboard, sourceApp: String?, excluding apps: [String]) -> Result {
        if let sourceApp, apps.contains(sourceApp) { return .ignored }
        let before = board.changeCount
        let types = Set((board.types ?? []).map(\.rawValue))
        guard ignoredTypes.isDisjoint(with: types),
              !types.contains(NSPasteboard.PasteboardType.fileURL.rawValue),
              let items = board.pasteboardItems, items.count == 1,
              let item = items.first else { return .ignored }
        let imageType: NSPasteboard.PasteboardType? = item.types.contains(.png) ? .png
            : (item.types.contains(.tiff) ? .tiff : nil)
        var allowed: [NSPasteboard.PasteboardType] = [.string, .rtf, .html]
        if let imageType { allowed.append(imageType) }
        var contents: [ClipboardContent] = []
        var bytes = 0
        for type in allowed where item.types.contains(type) {
            guard let data = item.data(forType: type), !data.isEmpty else { continue }
            bytes += data.count
            guard bytes <= maxItemBytes else { return .tooLarge }
            contents.append(.init(type: type.rawValue, data: data))
        }
        guard board.changeCount == before else { return .changedDuringRead }
        let captured = ClipboardItem(contents: contents, sourceApp: sourceApp)
        guard captured.imageData != nil || captured.text?.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty == false
        else { return .ignored }
        return .item(captured)
    }

    @discardableResult
    static func write(_ item: ClipboardItem, to board: NSPasteboard, plainText: Bool = false) -> Bool {
        let contents = plainText ? item.contents.filter { $0.type == NSPasteboard.PasteboardType.string.rawValue } : item.contents
        guard !contents.isEmpty else { return false }
        let output = NSPasteboardItem()
        for content in contents {
            guard output.setData(content.data, forType: .init(content.type)) else { return false }
        }
        output.setString("1", forType: ownType)
        board.clearContents()
        return board.writeObjects([output])
    }
}
